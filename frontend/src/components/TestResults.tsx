import { Terminal, CheckCircle2, AlertCircle, Loader2 } from 'lucide-react';
import { useRef, useEffect } from 'react';

interface TestResult {
  id: number;
  session_id: number;
  attempt: number;
  passed: boolean;
  total_tests: number;
  passed_tests: number;
  failed_tests: number;
  stdout: string;
  stderr: string;
  json_report: string;
  created_at: string;
}

interface ExecutionLog {
  id: number;
  session_id: number;
  log_text: string;
  created_at: string;
}

interface TestResultsProps {
  testResults: TestResult[];
  logs: ExecutionLog[];
  status: string;
  attempt: number;
  maxAttempts: number;
}

export default function TestResults({ testResults, logs, status, attempt, maxAttempts }: TestResultsProps) {
  const terminalEndRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    if (terminalEndRef.current) {
      terminalEndRef.current.scrollIntoView({ behavior: 'smooth' });
    }
  }, [logs]);

  const latestResult = testResults.length > 0 ? testResults[testResults.length - 1] : null;

  if (logs.length === 0) {
    if (['TESTING', 'TEST_GENERATION'].includes(status)) {
      return (
        <div className="flex flex-col items-center justify-center py-20 bg-green-card border border-green-border rounded-2xl p-6">
          <Loader2 className="h-8 w-8 animate-spin text-green-accent mb-3" />
          <p className="text-sm text-green-text font-medium">Launching Docker testing container...</p>
          <p className="text-xs text-green-muted mt-1">Spinning up environment and executing PyTest suites.</p>
        </div>
      );
    }
    return (
      <div className="flex flex-col items-center justify-center py-20 bg-green-card border border-green-border rounded-2xl p-6">
        <Terminal className="h-8 w-8 text-green-muted/40 mb-3" />
        <p className="text-sm text-green-muted font-medium">Sandbox execution logs are blank</p>
        <p className="text-xs text-green-muted/60 mt-1">Tests generated by the engine will be compiled and executed here.</p>
      </div>
    );
  }

  return (
    <div className="space-y-4 text-left animate-fade-in flex flex-col h-[520px]">
      {/* Configuration Metadata Cards */}
      <div className="grid grid-cols-3 gap-4 shrink-0">
        <div className="bg-green-card border border-green-border p-4 rounded-xl flex flex-col shadow-sm">
          <span className="text-[10px] text-green-muted uppercase tracking-wider font-semibold">Verification Attempt</span>
          <span className="text-base font-bold text-green-text mt-1.5">
            Loop {attempt} of {maxAttempts}
          </span>
        </div>

        {latestResult ? (
          <>
            <div className="bg-green-card border border-green-border p-4 rounded-xl flex flex-col shadow-sm">
              <span className="text-[10px] text-green-muted uppercase tracking-wider font-semibold">Test Coverage Passed</span>
              <span className="text-base font-bold text-emerald-500 mt-1.5">
                {latestResult.passed_tests} / {latestResult.total_tests} assertions
              </span>
            </div>

            <div className="bg-green-card border border-green-border p-4 rounded-xl flex flex-col shadow-sm">
              <span className="text-[10px] text-green-muted uppercase tracking-wider font-semibold">Sandbox Execution</span>
              <span className="text-base font-bold mt-1.5 flex items-center gap-1.5">
                {latestResult.passed ? (
                  <>
                    <CheckCircle2 className="h-4.5 w-4.5 text-emerald-500" />
                    <span className="text-emerald-500">PASSED</span>
                  </>
                ) : (
                  <>
                    <AlertCircle className="h-4.5 w-4.5 text-rose-500" />
                    <span className="text-rose-500">FAILED</span>
                  </>
                )}
              </span>
            </div>
          </>
        ) : (
          <div className="bg-green-card border border-green-border p-4 rounded-xl flex items-center justify-center col-span-2 shadow-sm">
            <span className="text-xs text-green-muted italic flex items-center gap-1.5">
              <Loader2 className="h-3.5 w-3.5 animate-spin text-green-accent" />
              Initializing sandbox execution report...
            </span>
          </div>
        )}
      </div>

      {/* Terminal View console */}
      <div className="flex-1 min-h-0 border border-green-border rounded-2xl bg-[#020603] flex flex-col shadow-2xl relative">
        {/* Terminal Header */}
        <div className="p-3 border-b border-green-border/80 text-[10px] font-mono text-green-muted/80 flex justify-between items-center px-4.5 shrink-0 bg-green-sidebar/10">
          <span className="flex items-center gap-1.5 font-bold uppercase tracking-wider">
            <Terminal className="h-4 w-4 text-green-accent" />
            <span>Docker Exec Sandbox Output</span>
          </span>
          <span className="h-2 w-2 rounded-full bg-emerald-500 animate-pulse" />
        </div>

        {/* Terminal Content */}
        <div className="flex-1 p-4.5 font-mono text-xs text-left leading-relaxed overflow-y-auto space-y-3.5 bg-black text-emerald-300">
          {logs.map((log) => (
            <div key={log.id} className="text-green-muted/80 border-b border-green-border/5 pb-1 last:border-0 last:pb-0">
              <span className="text-green-accent font-semibold mr-2 select-none">
                [{new Date(log.created_at).toLocaleTimeString()}]
              </span>
              <span>{log.log_text}</span>
            </div>
          ))}

          {/* Render pyTest log stdout details */}
          {latestResult && latestResult.stdout && (
            <div className="border-t border-green-border/10 pt-4.5 mt-4.5">
              <div className="text-emerald-500 font-bold mb-2">&gt;&gt; PyTest Log Details:</div>
              <pre className="text-emerald-200/90 bg-[#030804] p-4 rounded-xl border border-green-border/20 whitespace-pre-wrap overflow-x-auto text-[11px] leading-relaxed shadow-inner">
                {latestResult.stdout}
              </pre>
            </div>
          )}

          {latestResult && latestResult.stderr && (
            <div className="border-t border-green-border/10 pt-4.5 mt-4.5">
              <div className="text-rose-500 font-bold mb-2">&gt;&gt; Stderr Output Traceback:</div>
              <pre className="text-rose-300 bg-[#120505] p-4 rounded-xl border border-rose-950/30 whitespace-pre-wrap overflow-x-auto text-[11px] leading-relaxed">
                {latestResult.stderr}
              </pre>
            </div>
          )}

          <div ref={terminalEndRef} />
        </div>
      </div>
    </div>
  );
}
